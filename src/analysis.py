"""Post-hoc analysis of the test-split hypotheses in reports/hyps/*.jsonl (written by eval_* --hyps) -> reports/analysis.md + .json
 1. 95% bootstrap confidence intervals of CER per test set (utterance resampling, 2000 draws);
 2. paired bootstrap of the CER difference Stage 2 vs each baseline (same utterances);
 3. transliteration-tolerant code-switch scores (cs_metric.py) on MUCS;
 4. ML-SUPERB-2.0-style summary per system: mean CER over sets, worst set, standard deviation;
 5. 7x7 LID confusion (rows = true language, pooled over all test sets) for the Stage-2 decoder token, its LID-CTC head and ECAPA."""
import collections, json, os
import jiwer, numpy as np
from common import ROOT, LANGS, read_jsonl
from normalize import normalize
from cs_metric import cs_scores

R = f"{ROOT}/reports"
H = f"{R}/hyps"
SYSTEMS = [("s2_turbo", "oracle", "Stage 2 (oracle LID)"), ("s2_turbo", "pred", "Stage 2 (pred. LID)"),
           ("s2_turbo_fix", "oracle", "Stage 2 + fixes (oracle LID)"), ("s2_turbo_fix", "pred", "Stage 2 + fixes (pred. LID)"),
           ("vanilla_turbo", "oracle", "vanilla turbo"), ("indicconformer", "oracle", "IndicConformer"),
           ("qwen3asr-1.7b", "oracle", "Qwen3-ASR-1.7B"), ("qwen3asr-0.6b", "oracle", "Qwen3-ASR-0.6B")]
B = 2000
rng = np.random.default_rng(0)


def edits(ref, hyp, lang):
    """(character edits, reference characters) after the shared normalisation; None for an empty reference"""
    r, h = normalize(ref, lang), normalize(hyp or "", lang)
    if not r:
        return None
    o = jiwer.process_characters(r, h)
    return o.substitutions + o.deletions + o.insertions, o.hits + o.substitutions + o.deletions


def per_utt(rows, field):
    """{set: {id: (edits, ref_len)}}"""
    out = collections.defaultdict(dict)
    for r in rows:
        if r.get(field) is None:
            continue
        e = edits(r["ref"], r[field], r["lang"])
        if e:
            out[r["set"]][r["id"]] = e
    return out


def boot(ids, *systems):
    """bootstrap CER over the common ids; returns point estimates and (B, n_systems) draws"""
    E = np.array([[s[i][0] for s in systems] for i in ids], float)
    N = np.array([[s[i][1] for s in systems] for i in ids], float)
    idx = rng.integers(0, len(ids), (B, len(ids)))
    return E.sum(0) / N.sum(0), E[idx].sum(1) / N[idx].sum(1)


hyps = {n: read_jsonl(f"{H}/{n}.jsonl") for n in dict.fromkeys(s for s, _, _ in SYSTEMS) if os.path.exists(f"{H}/{n}.jsonl")}
systems = [(n, f, lab, per_utt(hyps[n], f)) for n, f, lab in SYSTEMS if n in hyps]
sets = sorted({s for _, _, _, u in systems for s in u})
res, out = {"ci": {}, "paired": {}, "cs": {}, "lid": {}}, ["# IE643 blanc — test-set analysis (auto-generated by src/analysis.py)\n"]

# 1. CIs
out.append(f"## CER with 95% bootstrap CI (test split, 100 utts/set, {B} resamples)\n")
out.append("| set | " + " | ".join(lab for _, _, lab, _ in systems) + " |\n|---|" + "---|" * len(systems))
for s in sets:
    cells = []
    for n, f, lab, u in systems:
        if s not in u:
            cells.append("-")
            continue
        p, d = boot(sorted(u[s]), u[s])
        lo, hi = np.percentile(d[:, 0], [2.5, 97.5])
        res["ci"].setdefault(s, {})[lab] = [float(p[0]), float(lo), float(hi)]
        cells.append(f"{p[0]:.3f} [{lo:.3f}, {hi:.3f}]")
    out.append(f"| {s} | " + " | ".join(cells) + " |")

# summary (sets every system covers, plus each system's own coverage)
out.append("\n## Summary over test sets (ML-SUPERB 2.0 style: mean / worst / std of per-set CER)\n")
common_sets = [s for s in sets if all(s in u for *_, u in systems)]
out.append(f"Common sets (covered by every system, {len(common_sets)}): " + ", ".join(common_sets) + "\n")
out.append("| system | sets | mean CER | worst set | std | mean CER (common sets) |\n|---|---|---|---|---|---|")
for n, f, lab, u in systems:
    c = {s: res["ci"][s][lab][0] for s in sets if lab in res["ci"].get(s, {})}
    w = max(c, key=c.get)
    cm = np.mean([c[s] for s in common_sets]) if common_sets else float("nan")
    res.setdefault("summary", {})[lab] = {"n_sets": len(c), "mean": float(np.mean(list(c.values()))), "worst": [w, c[w]],
                                          "std": float(np.std(list(c.values()))), "mean_common": float(cm)}
    out.append(f"| {lab} | {len(c)} | {np.mean(list(c.values())):.3f} | {w} {c[w]:.3f} | {np.std(list(c.values())):.3f} | {cm:.3f} |")

# 2. paired differences vs Stage 2 (oracle)
ref_sys = systems[0]
out.append("\n## Paired bootstrap: CER(baseline) − CER(Stage 2, oracle LID), 95% CI\n\nPositive = Stage 2 better. **bold** = CI excludes 0.\n")
others = [x for x in systems[1:]]
out.append("| set | " + " | ".join(lab for _, _, lab, _ in others) + " |\n|---|" + "---|" * len(others))
for s in sets:
    cells = []
    for n, f, lab, u in others:
        if s not in u or s not in ref_sys[3]:
            cells.append("-")
            continue
        ids = sorted(set(u[s]) & set(ref_sys[3][s]))
        p, d = boot(ids, u[s], ref_sys[3][s])
        diff, dd = p[0] - p[1], d[:, 0] - d[:, 1]
        lo, hi = np.percentile(dd, [2.5, 97.5])
        res["paired"].setdefault(s, {})[lab] = [float(diff), float(lo), float(hi)]
        txt = f"{diff:+.3f} [{lo:+.3f}, {hi:+.3f}]"
        cells.append(f"**{txt}**" if lo > 0 or hi < 0 else txt)
    out.append(f"| {s} | " + " | ".join(cells) + " |")

# 3. code-switch metric
out.append("\n## Code-switch (MUCS) with transliteration-tolerant scoring (see src/cs_metric.py)\n\n"
           "CER = plain normalized CER; rCER = CER after romanizing every script; sWER = WER on per-word consonant skeletons.\n")
out.append("| system | set | CER | rCER | sWER |\n|---|---|---|---|---|")
for n, f, lab, u in systems:
    for s in [x for x in sets if x.startswith("mucs/")]:
        rows = [r for r in hyps[n] if r["set"] == s and r.get(f) is not None]
        if not rows:
            continue
        lang = rows[0]["lang"]
        c = cs_scores([r["ref"] for r in rows], [r[f] for r in rows], lang)
        pairs = [(normalize(r["ref"], lang), normalize(r[f], lang)) for r in rows]
        cer = jiwer.cer([p for p, _ in pairs if p], [h for p, h in pairs if p])
        res["cs"].setdefault(s, {})[lab] = {"cer": cer, **c}
        out.append(f"| {lab} | {s} | {cer:.3f} | {c['rcer']:.3f} | {c['swer']:.3f} |")

# 4. LID confusion
def conf_table(title, pairs, cols):
    m = collections.defaultdict(collections.Counter)
    for t, p in pairs:
        m[t][p] += 1
    out.append(f"\n### {title}\n\nRows: true language (all test sets pooled); columns: predicted; last column: recall.\n")
    out.append("| true \\ pred | " + " | ".join(cols) + " | recall |\n|---|" + "---|" * (len(cols) + 1))
    for t in LANGS:
        if not m[t]:
            continue
        tot = sum(m[t].values())
        out.append(f"| {t} | " + " | ".join(str(m[t][c]) if m[t][c] else "·" for c in cols) + f" | {m[t][t] / tot:.2f} |")
    res["lid"][title] = {t: dict(m[t]) for t in LANGS if m[t]}


out.append("\n## LID confusion")
if "s2_turbo" in hyps:
    conf_table("Stage 2 — decoder language token", [(r["lang"], r["lid"]) for r in hyps["s2_turbo"]], LANGS)
    conf_table("Stage 2 — encoder LID-CTC head", [(r["lang"], r["lid_head"]) for r in hyps["s2_turbo"] if r.get("lid_head")], LANGS)
    conf_table("Stage 2 — decoder token, excluding svarah/en", [(r["lang"], r["lid"]) for r in hyps["s2_turbo"] if r["set"] != "svarah/en"], LANGS)
if "s2_turbo_fix" in hyps:
    conf_table("Stage 2 — calibrated rule (lid_calib.py: English bias + head fusion)", [(r["lang"], r["lid"]) for r in hyps["s2_turbo_fix"]], LANGS)
ec = json.load(open(f"{R}/baselines/ecapa_lid_test.json")) if os.path.exists(f"{R}/baselines/ecapa_lid_test.json") else None
if ec:
    pairs = [(k.split("/")[1], p) for k, v in ec.items() for p, c in v["closed_conf"].items() for _ in range(c)]
    conf_table("ECAPA VoxLingua107 (closed set; no Odia class)", pairs, [l for l in LANGS if l != "or"])

json.dump(res, open(f"{R}/analysis.json", "w"), indent=1, ensure_ascii=False)
open(f"{R}/analysis.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))
