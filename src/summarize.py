"""Build reports/experiments.md from runs/*/result.json and reports/{test,halluc,snr}_*.json."""
import json, os
from common import ROOT, LANGS

R = f"{ROOT}/reports"
out = ["# IE643 blanc — experiment results (auto-generated by src/summarize.py)\n"]


def load_json(p):
    return json.load(open(p)) if os.path.exists(p) else None


def run_result(name):
    return load_json(f"{ROOT}/runs/{name}/result.json")


def dev_table(runs, title, note=""):
    out.append(f"\n## {title}\n{note}\n")
    out.append("| run | trainable | utt/s | train min | group | CER | WER | LID(token) | LID(head) | loop |\n|---|---|---|---|---|---|---|---|---|---|")
    for n in runs:
        r = run_result(n)
        if not r:
            out.append(f"| {n} | NOT FINISHED | | | | | | | | |")
            continue
        for g, v in r["eval_final"].items():
            h = f"{v['lid_acc_head']:.2f}" if v.get("lid_acc_head") is not None else "-"
            out.append(f"| {n} | {r['trainable_M']:.1f}M | {r['utt_per_s']:.1f} | {r['train_time_s']/60:.0f} | {g} | {v['cer']:.3f} | {v['wer']:.3f} "
                       f"| {v['lid_acc']:.2f} | {h} | {v['loop_rate']:.2f} |")


def halluc_table(models, title):
    rows = [(lab, load_json(f"{R}/halluc_{n}.json")) for n, lab in models]
    rows = [(lab, h) for lab, h in rows if h]
    if not rows:
        return
    langs = [l for l in LANGS if any(l in h["hallucination"] for _, h in rows)]
    out.append(f"\n## {title}\n")
    out.append("| model | metric | " + " | ".join(langs) + " |\n|---|---|" + "---|" * len(langs))
    for lab, h in rows:
        for metric, fmt in [("hallucination", ".2f"), ("false_silence", ".2f"), ("mean_tokens_on_noise", ".1f")]:
            out.append(f"| {lab} | {metric} | " + " | ".join(format(h[metric][l], fmt) if l in h[metric] else "-" for l in langs) + " |")


def snr_tables(names):
    for n in names:
        j = load_json(f"{R}/{n}.json")
        if not j:
            continue
        conds = list(next(iter(j["cer"].values())).keys())
        out.append(f"\n### {n}  (CER by condition; held-out noise)\n")
        out.append("| set | " + " | ".join(conds) + " |\n|---|" + "---|" * len(conds))
        for k, v in j["cer"].items():
            out.append(f"| {k} | " + " | ".join(f"{v[c]['cer']:.3f}" for c in conds) + " |")


def test_table(name, title):
    """fine-tuned model on the held-out test split vs vanilla turbo and IndicConformer (same utterances)"""
    t = load_json(f"{R}/test_{name}.json")
    if not t:
        return
    van = load_json(f"{R}/baselines/whisper-large-v3-turbo_test.json") or {}
    ic = load_json(f"{R}/baselines/indicconformer_test.json") or {}
    f = lambda x: f"{x:.3f}" if x is not None else "-"
    out.append(f"\n## {title}\n\nCER/WER normalized, oracle language token unless stated. LID = decoder first-token argmax over the 7 "
               "languages; LID(head) = encoder LID-CTC head (blank if not evaluated).\n")
    out.append("| set | n | CER | WER | CER (pred. LID) | LID | LID(head) | vanilla turbo CER | IndicConformer CER |\n|---|---|---|---|---|---|---|---|---|")
    for k, v in sorted(t.items()):
        out.append(f"| {k} | {v['n']} | {f(v['oracle_norm']['cer'])} | {f(v['oracle_norm']['wer'])} | {f(v['pred_norm']['cer'])} "
                   f"| {f(v.get('lid_acc'))} | {f(v.get('lid_head_acc'))} | {f(van.get(k, {}).get('oracle_norm', {}).get('cer'))} "
                   f"| {f(ic.get(k, {}).get('norm', {}).get('cer'))} |")


e1 = run_result("e1_lora")
if e1 and "eval_step0" in e1:
    out.append("\n**Untrained Whisper-small, Hindi dev (reference):** " + ", ".join(f"{g}: CER {v['cer']:.3f}" for g, v in e1["eval_step0"].items()))
dev_table(["e1_lora", "e1_qlora", "e1_full"], "E1 — LoRA vs QLoRA vs full fine-tune (Whisper-small, Hindi only, 1000 steps, bs 32)")
dev_table(["e2_off", "e2_l0.1", "e2_l0.3", "e2_l1.0"], "E2 — LID-CTC head: lambda sweep (hi/te/as, LoRA, 1200 steps)",
          "LID(head) is the encoder LID-CTC head; LID(token) is the decoder language-token prediction at the first step.")
dev_table(["e3_unbalanced", "e3_balanced"], "E3 — balanced vs unbalanced sampling (hi/te/as, natural skew hi 97h / te 26h / as 5h)",
          "Same steps and batch size; balanced = Stage-2 upsampling of the same pool to equal hours.")
dev_table(["e2_off", "e4_aug", "e4_aug2"], "E4a — training with augmentation + non-speech blank-label data vs without (clean dev)")
halluc_table([("vanilla", "Whisper-small untrained"), ("e2_off", "LoRA, no aug/non-speech"), ("e4_aug", "LoRA + aug + non-speech (unweighted)"),
              ("e4_aug2", "LoRA + aug + non-speech (EOT weight 30)")],
             "E4b — non-speech hallucination and false silence (begin_suppress_tokens disabled; held-out MUSAN noise/music, 100 clips/lang)")
snr_tables(["snr_vanilla", "snr_e2_off", "snr_e4_aug", "snr_e4_aug2"])

dev_table(["s2_turbo"], "Stage 2 — Whisper large-v3-turbo + LoRA, 7 languages + MUCS, 11,000 steps (dev, final)")
test_table("s2_turbo", "Stage 2 — held-out TEST split (100 utts per set)")
test_table("s2_turbo_fix", "Stage 2 + decode-time fixes — TEST split (English decoded with non-ASCII tokens suppressed; LID = calibrated rule "
           "from lid_calib.py: English bias + LID-head fusion, fitted on dev + speaker-disjoint Svarah calibration data)")
halluc_table([("s2_turbo", "Stage 2 turbo")], "Stage 2 — non-speech hallucination and false silence (100 clips/lang)")
snr_tables(["snr_s2_turbo"])

out.append("\nConfidence intervals, paired bootstrap tests, transliteration-tolerant code-switch scores and LID confusion matrices: "
           "`reports/analysis.md` (src/analysis.py). Qwen3-ASR and ECAPA baselines: `reports/baselines/summary.md`.")
open(f"{R}/experiments.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))
